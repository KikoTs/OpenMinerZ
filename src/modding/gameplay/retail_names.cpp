std::optional<std::uint8_t> retail_block_from_name(std::string_view name) noexcept
{
    // "air" is what a script means by an empty cell.
    if (name == "air")
        return std::uint8_t{0U};
    for (std::size_t index{}; index < block_names.size(); ++index)
        if (block_names[index] == name)
            return static_cast<std::uint8_t>(index);
    return std::nullopt;
}

std::string_view retail_block_name(std::uint8_t block) noexcept
{
    return block < block_names.size() ? block_names[block] : std::string_view{};
}

std::optional<std::uint16_t> retail_item_from_name(std::string_view name) noexcept
{
    const auto found = std::ranges::find(item_names, name, &NamedItem::name);
    if (found == std::end(item_names))
        return std::nullopt;
    return found->id;
}

std::string_view retail_item_name(std::uint16_t item) noexcept
{
    const auto found = std::ranges::lower_bound(item_names, item, {}, &NamedItem::id);
    return found != std::end(item_names) && found->id == item ? found->name
                                                              : std::string_view{};
}

