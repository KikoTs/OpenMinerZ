using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

// Turns two probe runs (Classic 1.6.3.8 and Modern 1.9.9.8) into the tables the
// native client compiles in. The repository keeps short display strings as
// source data; this is the only place they come from, so a table can always be
// regenerated from the owned installs:
//
//   OpenMinerZ.PresentationParityProbe <classic dir> <out>\classic
//   OpenMinerZ.PresentationParityProbe <modern dir>  <out>\modern
//   OpenMinerZ.PresentationParityProbe --generate <out>\classic\presentation-facts.txt
//                                                 <out>\modern\presentation-facts.txt <repository root>
internal static class Generator
{
    private static Dictionary<string, string> Load(string path)
    {
        var facts = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (string line in File.ReadAllLines(path, Encoding.UTF8))
        {
            int index = line.IndexOf('=');
            if (index > 0) facts[line.Substring(0, index)] = line.Substring(index + 1);
        }
        return facts;
    }

    // Facts are stored escaped (\\, \r, \n). A C++ literal needs the same three
    // plus the quote; anything outside printable ASCII is written as UTF-8
    // octal escapes so the source file stays plain ASCII.
    private static string Literal(string escaped)
    {
        if (escaped == null) return "nullptr";
        var raw = new StringBuilder();
        for (int index = 0; index < escaped.Length; ++index)
        {
            char c = escaped[index];
            if (c == '\\' && index + 1 < escaped.Length)
            {
                char next = escaped[++index];
                raw.Append(next == 'n' ? '\n' : next == 'r' ? '\r' : next);
            }
            else raw.Append(c);
        }
        var text = new StringBuilder("\"");
        foreach (byte value in Encoding.UTF8.GetBytes(raw.ToString()))
        {
            if (value == '\\') text.Append("\\\\");
            else if (value == '"') text.Append("\\\"");
            else if (value == '\n') text.Append("\\n");
            else if (value == '\r') text.Append("\\r");
            else if (value == '?') text.Append("\\?");       // never a trigraph
            else if (value >= 32 && value < 127) text.Append((char)value);
            else text.Append("\\" + Convert.ToString(value, 8).PadLeft(3, '0'));
        }
        return text.Append('"').ToString();
    }

    private static string Identifier(string key)
    {
        string name = Regex.Replace(key, "[^A-Za-z0-9]+", "_").TrimEnd('_');
        if (name.Length == 0) name = "Empty";
        if (char.IsDigit(name[0])) name = "N" + name;
        return name;
    }

    private static uint Hash(IEnumerable<string> lines)
    {
        unchecked
        {
            uint hash = 2166136261u;
            foreach (string line in lines)
                foreach (byte value in Encoding.UTF8.GetBytes(line + "\n"))
                    hash = (hash ^ value) * 16777619u;
            return hash;
        }
    }

    private const string Banner =
        "// GENERATED by tools/OriginalClientInterop/PresentationParityProbe (--generate) from the\n" +
        "// shipped CastleMiner Z 1.6.3.8 and 1.9.9.8 assemblies. Do not edit by hand: rerun the probe.\n";

    public static int Run(string classicPath, string modernPath, string repository)
    {
        Dictionary<string, string> classic = Load(classicPath), modern = Load(modernPath);
        var stringsOut = new StringBuilder(Banner);
        stringsOut.Append("//\n// OPENMINERZ_RETAIL_STRING(identifier, resource key, 1.6.3.8 text, 1.9.9.8 text)\n");
        stringsOut.Append("// A build that has no such entry carries nullptr.\n");

        // The game's Strings table first, then DNA.Common's shared dialog words
        // (OK, Cancel, On, Off ...) under a Common_ prefix.
        var rows = new List<Tuple<string, string, string, string>>();
        var used = new HashSet<string>(StringComparer.Ordinal);
        Action<string, string> collect = (prefix, identifierPrefix) =>
        {
            foreach (string key in classic.Keys.Concat(modern.Keys).Where(k => k.StartsWith(prefix, StringComparison.Ordinal))
                         .Distinct().OrderBy(k => k, StringComparer.Ordinal))
            {
                string resourceKey = key.Substring(prefix.Length);
                if (prefix == "string." && resourceKey == "count") continue;
                string identifier = identifierPrefix + Identifier(resourceKey);
                if (identifierPrefix.Length == 0 && identifier[0] == '_' && identifier.Length > 1 && char.IsDigit(identifier[1]))
                    identifier = "N" + identifier.Substring(1);
                if (!used.Add(identifier)) throw new InvalidDataException("Identifier collision: " + identifier);
                string c, m;
                classic.TryGetValue(key, out c);
                modern.TryGetValue(key, out m);
                rows.Add(Tuple.Create(identifier, resourceKey, c, m));
            }
        };
        collect("string.", "");
        collect("resource.DNA.CommonResources.", "Common_");
        foreach (var row in rows)
            stringsOut.Append("OPENMINERZ_RETAIL_STRING(" + row.Item1 + ", \"" + row.Item2 + "\", " +
                              Literal(row.Item3) + ", " + Literal(row.Item4) + ")\n");
        Write(repository, @"include\openminerz\retail_strings.inc", stringsOut);

        // ---------------------------------------------------------------- items
        var itemsOut = new StringBuilder(Banner);
        itemsOut.Append("//\n// OPENMINERZ_RETAIL_ITEM(InventoryItemId value, InventoryItemIDs name,\n");
        itemsOut.Append("//     1.6.3.8 Name, Description1, Description2, 1.9.9.8 Name, Description)\n");
        itemsOut.Append("// nullptr name: InventoryItem.Initalize registers no class for the id in that build.\n");
        itemsOut.Append("// 1.9.9.8 ordinals 123..154 are the native enum's 256..287 (see inventory.hpp).\n");
        var itemIds = new SortedSet<int>();
        foreach (var facts in new[] { classic, modern })
            foreach (string key in facts.Keys)
                if (key.StartsWith("item.", StringComparison.Ordinal) && key.EndsWith(".enum", StringComparison.Ordinal))
                    itemIds.Add(int.Parse(key.Split('.')[1], CultureInfo.InvariantCulture));
        foreach (int id in itemIds)
        {
            string key = "item." + id + ".";
            bool inClassic = classic.ContainsKey(key + "name"), inModern = modern.ContainsKey(key + "name");
            if (inClassic && inModern && classic[key + "enum"] != modern[key + "enum"])
                throw new InvalidDataException("Item id " + id + " names different classes in the two builds");
            int native = id >= 123 ? id + 133 : id;
            itemsOut.Append("OPENMINERZ_RETAIL_ITEM(" + native + ", " + (inModern ? modern : classic)[key + "enum"] + ", " +
                            Literal(inClassic ? classic[key + "name"] : null) + ", " +
                            Literal(inClassic ? classic[key + "description1"] : null) + ", " +
                            Literal(inClassic ? classic[key + "description2"] : null) + ", " +
                            Literal(inModern ? modern[key + "name"] : null) + ", " +
                            Literal(inModern ? modern[key + "description"] : null) + ")\n");
        }
        Write(repository, @"src\retail_item_text.inc", itemsOut);

        // --------------------------------------------------------------- blocks
        var blocksOut = new StringBuilder(Banner);
        blocksOut.Append("//\n// OPENMINERZ_RETAIL_BLOCK(BlockTypeEnum value, BlockTypeEnum name, 1.6.3.8 BlockType.Name, 1.9.9.8 BlockType.Name)\n");
        int blockCount = int.Parse(modern["block.count"], CultureInfo.InvariantCulture);
        int classicBlocks = int.Parse(classic["block.count"], CultureInfo.InvariantCulture);
        for (int block = 0; block < blockCount; ++block)
        {
            string key = "block." + block + ".";
            blocksOut.Append("OPENMINERZ_RETAIL_BLOCK(" + block + ", " + modern[key + "enum"] + ", " +
                             Literal(block < classicBlocks ? classic[key + "name"] : null) + ", " +
                             Literal(modern[key + "name"]) + ")\n");
        }
        Write(repository, @"src\world\retail_block_names.inc", blocksOut);

        // --------------------------------------------------------- achievements
        var achievementsOut = new StringBuilder(Banner);
        achievementsOut.Append("//\n// OPENMINERZ_RETAIL_ACHIEVEMENT(index, Steam API name, Name, HowToUnlock) - identical in both builds.\n");
        int achievements = int.Parse(modern["achievement.count"], CultureInfo.InvariantCulture);
        for (int index = 0; index < achievements; ++index)
        {
            string key = "achievement." + index + ".";
            foreach (string field in new[] { "api", "name", "how" })
                if (classic[key + field] != modern[key + field])
                    throw new InvalidDataException("Achievement " + index + " differs between the builds");
            achievementsOut.Append("OPENMINERZ_RETAIL_ACHIEVEMENT(" + index + ", " + Literal(modern[key + "api"]) + ", " +
                                   Literal(modern[key + "name"]) + ", " + Literal(modern[key + "how"]) + ")\n");
        }
        Write(repository, @"src\retail_achievements.inc", achievementsOut);

        // ---------------------------------------------------------------- pinned
        // What the native test holds the tables to. Strings are pinned by count
        // and hash (the live differential compares every one); items, blocks,
        // achievements, fonts and cue names are pinned in full.
        var pinned = new StringBuilder(Banner);
        pinned.Append("#pragma once\n\n#include <array>\n#include <string_view>\n\nnamespace openminerz::presentation_pinned\n{\n\n");
        pinned.Append("struct Fact final\n{\n    std::string_view key;\n    std::string_view value;\n};\n\n");
        foreach (var generation in new[] { Tuple.Create("classic", classic), Tuple.Create("modern", modern) })
        {
            Dictionary<string, string> facts = generation.Item2;
            var stringLines = facts.Where(fact => fact.Key.StartsWith("string.", StringComparison.Ordinal) && fact.Key != "string.count")
                .OrderBy(fact => fact.Key, StringComparer.Ordinal).Select(fact => fact.Key + "=" + fact.Value).ToList();
            var keep = facts.Where(fact =>
                    fact.Key.StartsWith("item.", StringComparison.Ordinal) || fact.Key.StartsWith("block.", StringComparison.Ordinal) ||
                    fact.Key.StartsWith("achievement.", StringComparison.Ordinal) || fact.Key.StartsWith("font.", StringComparison.Ordinal) ||
                    fact.Key.StartsWith("cue.", StringComparison.Ordinal) || fact.Key == "info.assembly")
                .Where(fact => !fact.Key.EndsWith(".class", StringComparison.Ordinal))
                .OrderBy(fact => fact.Key, StringComparer.Ordinal).ToList();
            keep.Add(new KeyValuePair<string, string>("string.count", stringLines.Count.ToString(CultureInfo.InvariantCulture)));
            keep.Add(new KeyValuePair<string, string>("string.hash", Hash(stringLines).ToString("x8")));
            pinned.Append("inline constexpr std::array<Fact, " + keep.Count + "> " + generation.Item1 + "{{\n");
            foreach (var fact in keep)
                pinned.Append("    {\"" + fact.Key + "\", " + Literal(fact.Value) + "},\n");
            pinned.Append("}};\n\n");
        }
        pinned.Append("} // namespace openminerz::presentation_pinned\n");
        Write(repository, @"tests\presentation_parity_pinned.hpp", pinned);
        return 0;
    }

    private static void Write(string repository, string relative, StringBuilder text)
    {
        string path = Path.Combine(repository, relative);
        File.WriteAllText(path, text.ToString().Replace("\r\n", "\n"), new UTF8Encoding(false));
        Console.WriteLine("wrote " + path);
    }
}
